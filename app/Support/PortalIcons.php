    /**
     * The inner SVG for an icon - for callers that draw their own <svg>
     * around it, like the phone tab bar.
     *
     * @throws InvalidArgumentException when no icon has that name, so a typo
     *                                  fails loudly instead of leaving a blank
     *                                  space where the icon should be.
     */
    public static function paths(string $name): string
    {
        if (! isset(self::PATHS[$name])) {
            throw new InvalidArgumentException("There is no portal icon named [{$name}].");
        }

        return self::PATHS[$name];
    }

    /**
     * A whole icon. Sized by its container's CSS unless a size is given.
     */
    public static function svg(string $name, ?int $size = null, float $strokeWidth = 2): string
    {
        $dimensions = $size ? " width=\"{$size}\" height=\"{$size}\"" : '';

        return '<svg viewBox="0 0 24 24"'.$dimensions.' fill="none" stroke="currentColor" stroke-width="'.$strokeWidth.'"'
            .' stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"'
            .' data-icon="'.$name.'">'.self::paths($name).'</svg>';
    }

    /**
     * Every icon name there is.
     *
     * @return list<string>
     */
    public static function names(): array
    {
        return array_keys(self::PATHS);
    }
